const preference = 'ooa-language';
let language = 'zh-CN';
try {
  if (localStorage.getItem(preference) === 'en') language = 'en';
} catch { /* storage is optional */ }

export const locale = () => language;

export function setLocale(value) {
  language = value === 'en' ? 'en' : 'zh-CN';
  try { localStorage.setItem(preference, language); } catch { /* keep the in-memory preference */ }
}

export function t(message, params = {}) {
  const value = language === 'en' && Object.hasOwn(english, message) ? english[message] : message;
  return value.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(params, name) ? params[name] : token);
}
